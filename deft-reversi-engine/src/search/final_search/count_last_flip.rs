/// 1 マスだけ空いている盤面で、空きマス `pos` に着手したときに反転する石数の 2 倍を返す。
///
/// `player` が `pos` に対して反転を取れない場合は 0 を返す。スコア計算の都合で
/// 「反転数 × 2」を返すことに注意(テーブルにそうエンコードされている)。
#[cfg(not(target_feature = "bmi2"))]
#[inline(always)]
pub(crate) fn count_last_flip(pos: usize, p: u64) -> i32 {
    debug_assert!(pos < 64);

    let x = pos & 0x07;
    let y = pos >> 3;
    let count_flip_x = &COUNT_FLIP[x];

    let mut n_flipped = 0usize;
    n_flipped += COUNT_FLIP[y]
        [((((p >> x) & 0x0101010101010101).wrapping_mul(0x0102040810204080)) >> 56) as usize]
        as usize;
    n_flipped += count_flip_x[(p >> (y * 8)) as u8 as usize] as usize;
    n_flipped += count_flip_x
        [(((p & MASK_D[0][pos]).wrapping_mul(0x0101010101010101)) >> 56) as usize]
        as usize;
    n_flipped += count_flip_x
        [(((p & MASK_D[1][pos]).wrapping_mul(0x0101010101010101)) >> 56) as usize]
        as usize;

    n_flipped as i32
}

#[cfg(target_feature = "bmi2")]
use std::arch::x86_64::_pext_u64;

/// BMI2 の `_pext_u64` を用いた高速版。
///
/// PEXT は Intel では非常に速いが、AMD Zen2 までは microcode 実装でかなり遅い点に注意。
#[cfg(target_feature = "bmi2")]
#[inline(always)]
pub(crate) fn count_last_flip(pos: usize, mut p: u64) -> i32 {
    debug_assert!(pos < 64);

    let h = pos & 7;
    let v = pos >> 3;
    let mask_x = &MASK_X[pos].0;

    p &= mask_x[3]; // 関係ないビットをマスクして外側のダミーを作る
    let mut n_flipped = COUNT_FLIP[h][((p >> (pos & 0x38)) & 0xFF) as usize] as usize;
    unsafe {
        n_flipped += COUNT_FLIP[v][_pext_u64(p, mask_x[0]) as usize] as usize;
        n_flipped += COUNT_FLIP[v][_pext_u64(p, mask_x[1]) as usize] as usize;
        n_flipped += COUNT_FLIP[v][_pext_u64(p, mask_x[2]) as usize] as usize;
    }
    n_flipped as i32
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::board::board::Board;

    /// 1 マスだけ空いている盤面 (player と opponent で 63 マス埋まっている) でも一致するか確認する。
    ///
    /// `count_last_flip` は `~player` を opponent と解釈するため、1 マス残り以外の盤面では
    /// 一般に `Board::flip_bit` と一致しない点に注意。本関数は 1 マス残り専用。
    #[test]
    fn count_last_flip_one_empty_matches_flip_bit_count() {
        let mut rng_state = 0xdeadbeef_cafebabe_u64;
        for _ in 0..200 {
            for empty_pos in 0..64usize {
                let empty_bit = 1u64 << empty_pos;
                let player = next_pseudo_random(&mut rng_state) & !empty_bit;
                let opponent = !player & !empty_bit;
                let board = Board { player, opponent };
                let expected = (board.flip_bit(empty_bit).count_ones() as i32) * 2;
                let actual = count_last_flip(empty_pos, player);
                assert_eq!(
                    actual, expected,
                    "mismatch at pos={empty_pos}, player={player:#018x}",
                );
            }
        }
    }

    fn next_pseudo_random(state: &mut u64) -> u64 {
        *state ^= state.wrapping_shl(13);
        *state ^= state.wrapping_shr(7);
        *state ^= state.wrapping_shl(17);
        *state
    }
}
