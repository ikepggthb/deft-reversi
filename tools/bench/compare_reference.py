#!/usr/bin/env python3
"""Build the legacy/current API comparator with an explicitly supplied old checkout."""
import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess

REPO = Path(__file__).resolve().parents[2]


def prepare(old_engine, project):
    old_engine = old_engine.resolve()
    project = project.resolve()
    if not (old_engine / 'Cargo.toml').is_file():
        raise ValueError(f'old engine Cargo.toml not found: {old_engine}')
    if project == old_engine or project == REPO:
        raise ValueError('project must be a separate generated directory')
    (project / 'src').mkdir(parents=True, exist_ok=True)
    # JSON string quoting is valid TOML basic-string quoting, including spaces.
    old_path = json.dumps(str(old_engine), ensure_ascii=False)
    new_path = json.dumps(str(REPO / 'deft-reversi-engine'), ensure_ascii=False)
    manifest = f'''# Generated by tools/bench/compare_reference.py; do not edit.
[package]
name = "deft-engine-compare"
version = "0.1.0"
edition = "2024"
publish = false
[workspace]
[dependencies]
old = {{ package = "deft_reversi_engine", path = {old_path} }}
new = {{ package = "deft_reversi_engine", path = {new_path} }}
[profile.release]
lto = "fat"
codegen-units = 1
panic = "unwind"
'''
    (project / 'Cargo.toml').write_text(manifest)
    shutil.copyfile(Path(__file__).parent / 'reference/main.rs', project / 'src/main.rs')
    return project


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--old-engine', type=Path, required=True,
                        help='directory containing the legacy engine Cargo.toml')
    parser.add_argument('--project', type=Path, default=REPO / 'target/reference-compare',
                        help='generated standalone Cargo project; retain its lockfile for replay')
    parser.add_argument('--prepare-only', action='store_true')
    parser.add_argument('--offline', action='store_true')
    parser.add_argument('arguments', nargs=argparse.REMAINDER,
                        help='after --: OLD_MODEL NEW_MODEL POSITIONS level:60 ROUNDS [THREADS]')
    args = parser.parse_args()
    try:
        project = prepare(args.old_engine, args.project)
    except ValueError as error:
        parser.error(str(error))
    print(project / 'Cargo.toml', flush=True)
    if args.prepare_only:
        return
    cargo = os.environ.get('CARGO', 'cargo')
    # This independent project's dependency graph has its own lockfile.
    command = [cargo, '+1.99.1', 'generate-lockfile', '--manifest-path', str(project / 'Cargo.toml')]
    if args.offline:
        command.append('--offline')
    if not (project / 'Cargo.lock').exists():
        subprocess.run(command, check=True)
    command = [cargo, '+1.99.1', 'run', '--locked', '--release', '--manifest-path',
               str(project / 'Cargo.toml')]
    if args.offline:
        command.append('--offline')
    arguments = args.arguments[1:] if args.arguments[:1] == ['--'] else args.arguments
    subprocess.run([*command, '--', *arguments], check=True)


if __name__ == '__main__':
    try:
        main()
    except subprocess.CalledProcessError as error:
        raise SystemExit(error.returncode)
